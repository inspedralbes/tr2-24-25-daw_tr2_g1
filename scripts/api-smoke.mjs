import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const base=process.env.TEST_API_URL || 'http://127.0.0.1:8059';
let checks=0;
const check=(actual,expected,message)=>{assert.deepEqual(actual,expected,message);checks++;};
const request=async(path,body,method=body?'POST':'GET')=>{
 const response=await fetch(base+path,{method,...(body?{headers:{'Content-Type':'application/json'},body:JSON.stringify(body)}:{})});
 return {status:response.status,body:await response.json()};
};
check((await request('/up')).status,200,'database health');
const profile=await request('/api/demo/profile');
check(profile.body.centre.email,'centre@example.invalid','synthetic centre');
check((await request('/api/demo/profile?role=professor')).body.centre.esProfesor,true,'teacher access');
check((await request('/api/login-google',{id_token:'invalid'})).status,403,'Google disabled');
check((await request('/api/admin/create-user',{email:'other@example.invalid',centre_id:835})).status,403,'admin write disabled');
check((await request('/api/admin/users/1',undefined,'DELETE')).status,403,'admin delete disabled');
const ralc='99'+Math.floor(Math.random()*1000000).toString().padStart(6,'0');
check((await request('/api/alumne',{ralc,name:'PRIVATE INPUT',surname:'PRIVATE INPUT',dni:'12345678Z',date:'2000-01-01',centre_procedencia_id:836})).status,200,'create demo student');
let student=(await request('/api/alumne/'+ralc)).body.data;
check(student.nom,'Alumne Demo','never save visitor name');
check(student.dni,'00000000T','never save visitor ID');
check(student.centreProcedencia,'Centre Demo Barcelona','fixed demo centre');
check((await request('/api/alumne',{ralc:'../escape',name:'Example'})).status,400,'path-like ID rejected');
check((await request('/api/alumne/plan_individualitzat',{ralc,justificacio:'PRIVATE INPUT'})).status,201,'create PI');
student=(await request('/api/alumne/'+ralc)).body.data;
check(student.pis[0].justificacio.includes('precalculada'),true,'persist only example analysis');
const form=new FormData();
form.append('ralc',ralc);form.append('pdfFile',new Blob(['PRIVATE INPUT'],{type:'application/pdf'}),'private.pdf');
form.append('observacio','PRIVATE INPUT');
check((await fetch(base+'/api/save-pi',{method:'POST',body:form})).status,200,'save PI through original upload controller');
const pdf=await fetch(base+'/api/pdf/'+ralc);
check(pdf.status,200,'PDF accessible');
const expected=await readFile(new URL('../backend/demo/informe-demo.pdf',import.meta.url));
